#!/usr/bin/env python3
"""Pull the subclass spell tables out of Xanathar's and Tasha's.

Domain, oath, circle, patron and specialist spell tables are printed beside
body text in two columns, so the OCR runs a table row and a sentence of prose
together on one line. Rather than trying to find where the row ends, each line
is matched against the spell database: the longest run of known spell names at
the start of the row is the row's content, and the prose that follows simply
fails to match.

The rows of a table are in ascending order, and how many spells each row holds
is fixed by the kind of subclass, so the extracted names are assigned to
levels by position. The count is printed for review.

Output is the '|' separated form that data_subclasses.c expects.
"""

import os
import re
import sys

