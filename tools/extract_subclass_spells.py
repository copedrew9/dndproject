def spell_index():
    """Every spell name in the generated database, keyed canonically."""
    src = open(os.path.join(ROOT, "src", "data_spells.c")).read()
    names = re.findall(r'^\s*\{ "((?:[^"\\]|\\.)*)",', src, re.M)
    return {E.canon(n): n for n in names}


def longest_spell_prefix(words, index):
    """Longest run of words from the start that names a spell."""
    for take in range(min(len(words), 6), 0, -1):
        key = E.canon(" ".join(words[:take]))
        if key in index:
            return index[key], take
    return None, 0


def parse_row(line, index, want):
    """Reads up to `want` spell names from the start of a table row."""
    body = line.strip()
    if not body:
        return []

    # Drop a leading level marker: the first token, when it is not itself
    # the start of a spell name ("1st", "Sth", "lai", "Cleric Level").
    words = body.replace(",", " , ").split()
    found = []
    while words and len(found) < want:
        if words[0] == ",":
            words.pop(0)
            continue
        name, used = longest_spell_prefix([w for w in words if w != ","], index)
        if name is None:
            # Skip one token and try again, but only before anything matched;
            # once a spell has been read, an unmatched token is prose.
            if found:
                break
            words.pop(0)
            continue
        found.append(name)
        # Consume the words the match used, ignoring the comma placeholders.
        consumed = 0
        while words and consumed < used:
            if words[0] != ",":
                consumed += 1
            words.pop(0)
    return found


def main():
    index = spell_index()
    print("/* Generated by tools/extract_subclass_spells.py -- review before use. */")
    problems = 0

    for path, line_no, name, per_row, rows in TABLES:
        lines = E.load_lines(path)
        want_total = per_row * rows
        collected = []

        for raw in lines[line_no: line_no + 60]:
            if len(collected) >= want_total:
                break
            got = parse_row(raw, index, per_row)
            if got:
                collected.append(got)

        flat = [s for row in collected for s in row]
        status = "ok" if len(flat) == want_total else "MISMATCH"
        if status != "ok":
            problems += 1

        print('\n/* %-22s %s: %d of %d spells */' %
              (name, status, len(flat), want_total))
        groups = []
        for row in collected[:rows]:
            groups.append(", ".join(s.lower() for s in row))
        print('  "%s"' % "|".join(groups))

    if problems:
        print("\n/* %d table(s) need checking by hand */" % problems)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
