def build_world():
    tags = by_tag(read_file("world.txt"))
    out = Out(os.path.join(SRC, "gen_world.c"), "data/world.txt")
    out.w('#include "data.h"\n')

    out.table(
        "const Deity DEITIES[]",
        ["    { %s, %s,\n      %s, %s,\n      %s, %s }"
         % (cstr(r.str(0)), cstr(r.str(1)), cstr(r.str(2)), cstr(r.str(3)),
            cstr(r.str(4)), cstr(r.str(5)))
         for r in tags.get("DEITY", [])],
        "DEITY_COUNT")

    out.table(
        "const ConditionData CONDITIONS[]",
        ["    { %s,\n      %s }" % (cstr(r.str(0)), cstr(r.str(1)))
         for r in tags.get("CONDITION", [])],
        "CONDITION_COUNT")

    sizes = [r.str(0) for r in tags.get("BEASTSIZE", [])]
    if len(sizes) != 6:
        sys.exit("data/world.txt: expected 6 BEASTSIZE lines, found %d"
                 % len(sizes))
    out.table("const char *const BEAST_SIZE_NAME[]",
              ["    " + cstr(s) for s in sizes])
    size_id = dict((s, "BSIZE_" + s.upper()) for s in sizes)

    rows = []
    for r in tags.get("BEAST", []):
        rows.append(
            "    { %s, %s, %d, %d, %d,\n      %s,\n      {%s},\n"
            "      %s, %s }"
            % (cstr(r.str(0)), lookup(size_id, r, 1, "size"), r.int(2),
               r.int(3), r.int(4), cstr(r.str(5)),
               ",".join(str(r.int(6 + k)) for k in range(6)),
               cstr(r.str(12)), cstr(r.str(13))))
    out.table("const BeastData BEASTS[]", rows, "BEAST_COUNT_ACTUAL")

    sk = [r.str(0) for r in tags.get("SIDEKICKCLASS", [])]
    if len(sk) != 3:
        sys.exit("data/world.txt: expected 3 SIDEKICKCLASS lines, found %d"
                 % len(sk))
    out.table("const char *const SIDEKICK_CLASS_NAME[SK_CLASS_COUNT]",
              ["    " + cstr(r.str(0)) for r in tags["SIDEKICKCLASS"]])
    out.table("const char *const SIDEKICK_CLASS_BLURB[SK_CLASS_COUNT]",
              ["    " + cstr(r.str(1), 4) for r in tags["SIDEKICKCLASS"]])

    roles = tags.get("SIDEKICKROLE", [])
    if len(roles) != 3:
        sys.exit("data/world.txt: expected 3 SIDEKICKROLE lines, found %d"
                 % len(roles))
    out.table("const char *const SPELLCASTER_ROLE_NAME[SK_ROLE_COUNT]",
              ["    " + cstr(r.str(0)) for r in roles])
    out.table("const char *const SPELLCASTER_ROLE_DESC[SK_ROLE_COUNT]",
              ["    " + cstr(r.str(1), 4) for r in roles])

    sk_id = dict((r.str(0), "SK_" + r.str(0).upper()) for r in sk_rows(tags))
    rows = []
    for r in tags.get("SIDEKICKFEATURE", []):
        rows.append("    { %s, %d, %s,\n      %s }"
                    % (lookup(sk_id, r, 0, "sidekick class"), r.int(1),
                       cstr(r.str(2)), cstr(r.str(3))))
    out.table("const SidekickFeature SIDEKICK_FEATURES[]", rows,
              "SIDEKICK_FEATURE_COUNT")

    progs = {}
    for r in tags.get("PROGRESSION", []):
        vals = [v.strip() for v in r.str(1).split(",")]
        if len(vals) != 21:
            r.die("%r has %d levels, expected 21" % (r.str(0), len(vals)))
        progs[r.str(0)] = vals
    for key, cname in (("sidekick spellcaster cantrips",
                        "SPELLCASTER_CANTRIPS"),
                       ("sidekick spellcaster spells known",
                        "SPELLCASTER_SPELLS_KNOWN")):
        if key not in progs:
            sys.exit("data/world.txt: no PROGRESSION named %r" % key)
        out.w("\nconst unsigned char %s[MAX_LEVEL + 1] = {\n    %s\n};\n"
              % (cname, ", ".join(progs[key])))

    # --- the background tables, each row carrying the rolls that produce it
    rows_by_table = {}
    for r in tags.get("LIFEROW", []):
        rows_by_table.setdefault(r.str(0), []).append(r)
    tables = tags.get("LIFETABLE", [])
    out.w("\n/* Xanathar's background tables. */\n")
    for n, t in enumerate(tables):
        name = t.str(0)
        if name not in rows_by_table:
            t.die("no LIFEROW lines belong to %r" % name)
        out.w("static const LifeEntry LIFEROWS_%d[] = {\n" % n)
        for r in rows_by_table[name]:
            if r.int(1) > r.int(2):
                r.die("%d-%d runs backwards" % (r.int(1), r.int(2)))
            out.w("    { %d, %d, %s },\n"
                  % (r.int(1), r.int(2), cstr(r.str(3))))
        out.w("};\n")
    named = set(t.str(0) for t in tables)
    for name, rs in rows_by_table.items():
        if name not in named:
            rs[0].die("no LIFETABLE named %r" % name)

    out.table(
        "const LifeTable LIFE_TABLES[]",
        ["    { %s, %s,\n      LIFEROWS_%d,"
         " (int)(sizeof(LIFEROWS_%d) / sizeof(LIFEROWS_%d[0])) }"
         % (cstr(t.str(0)), cstr(t.str(1)), n, n, n)
         for n, t in enumerate(tables)],
        "LIFE_TABLE_COUNT")

    out.save()


def sk_rows(tags):
    return tags.get("SIDEKICKCLASS", [])


# --------------------------------------------------------------------- main


def main():
    classes, subclasses = build_character()
    build_equipment()
    build_spells()
    build_world()
    print("%d classes, %d subclasses" % (len(classes), len(subclasses)))


if __name__ == "__main__":
    main()
