#!/usr/bin/env python3
"""build_data.py -- turn the data files under data/ into C tables.

The game data is hand-written, in four line-oriented files under data/. This
reads them and writes the four src/gen_*.c files the program compiles. The C
is generated so that adding a race or a magic item means editing one text
line, not finding the right initialiser in the right table.

Nothing here reads the OCR dumps in TextFiles/. Those are kept only so
tools/audit.py can check what is written here against the books.

Every cross-reference is resolved by name -- a feature names its class, a
subrace names its race -- and an unresolved name is an error that stops the
run before anything is written. That replaces the checking the compiler used
to do when the tables were C.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "data")
SRC = os.path.join(ROOT, "src")

# ---------------------------------------------------------------- the format


class Rec:
    """One record: its tag, its fields, and where it came from."""

    def __init__(self, tag, fields, where):
        self.tag = tag
        self.f = fields
        self.where = where

    def str(self, i):
        if i >= len(self.f):
            self.die("expected at least %d fields, found %d" % (i + 1,
                                                                len(self.f)))
        return self.f[i]

    def int(self, i):
        s = self.str(i).strip()
        try:
            return int(s)
        except ValueError:
            self.die("field %d: expected a number, found %r" % (i + 1, s))

    def die(self, msg):
        sys.exit("%s: %s: %s" % (self.where, self.tag, msg))


def split_fields(line):
    """Split on '|', honouring the '\\|' and '\\\\' escapes."""
    out, cur, i = [], [], 0
    while i < len(line):
        c = line[i]
        if c == "\\" and i + 1 < len(line):
            cur.append(line[i + 1])
            i += 2
        elif c == "|":
            out.append("".join(cur))
            cur = []
            i += 1
        else:
            cur.append(c)
            i += 1
    out.append("".join(cur))
    return out


def read_file(name):
    """Records from one data file, in the order they appear."""
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        sys.exit("build_data: missing %s" % path)

    recs, pending, start = [], None, 0
    for n, raw in enumerate(open(path, encoding="utf-8"), 1):
        line = raw.rstrip("\n").rstrip("\r")
        if pending is None and (not line.strip() or line.lstrip()[0] == "#"):
            continue
        # A line ending in an odd number of backslashes continues; the last
        # one is the continuation mark and the rest are escapes.
        trail = len(line) - len(line.rstrip("\\"))
        if trail % 2 == 1:
            line = line[:-1]
            if pending is None:
                pending, start = line, n
            else:
                pending += line
            continue
        if pending is not None:
            line, pending = pending + line, None
        else:
            start = n
        fields = split_fields(line)
        recs.append(Rec(fields[0], fields[1:], "%s:%d" % (name, start)))
    if pending is not None:
        sys.exit("%s:%d: file ends in a continuation" % (name, start))
    return recs


def by_tag(recs):
    out = {}
    for r in recs:
        out.setdefault(r.tag, []).append(r)
    return out


# ------------------------------------------------------------ writing the C


def cstr(s, indent=6):
    """A C string literal, wrapped at word boundaries so it stays readable."""
    esc = s.replace("\\", "\\\\").replace('"', '\\"')
    if len(esc) <= 60:
        return '"%s"' % esc
    parts, cur = [], ""
    for word in esc.split(" "):
        if cur and len(cur) + len(word) + 1 > 60:
            parts.append(cur + " ")
            cur = word
        else:
            cur = (cur + " " + word) if cur else word
    parts.append(cur)
    pad = "\n" + " " * indent
    return pad.join('"%s"' % p for p in parts)


class Out:
    def __init__(self, path, source, note=""):
        self.path = path
        self.buf = []
        self.w("/* %s -- generated from %s by tools/build_data.py.\n"
               " *\n"
               " * Do not edit this file: edit %s and run `make data`.%s\n"
               " */\n" % (os.path.basename(path), source, source,
                          ("\n *\n * " + note) if note else ""))

    def w(self, s):
        self.buf.append(s)

    def table(self, decl, rows, count_name=None):
        self.w("\n%s = {\n" % decl)
        for r in rows:
            self.w("%s,\n" % r)
        self.w("};\n")
        if count_name:
            name = decl.split("[")[0].split()[-1]
            self.w("const int %s =\n    (int)(sizeof(%s) / sizeof(%s[0]));\n"
                   % (count_name, name, name))

    def save(self):
        text = "".join(self.buf)
        old = None
        if os.path.exists(self.path):
            old = open(self.path, encoding="utf-8").read()
        if old != text:
            open(self.path, "w", encoding="utf-8").write(text)
            print("wrote %s" % os.path.relpath(self.path, ROOT))
        else:
            print("%s unchanged" % os.path.relpath(self.path, ROOT))


