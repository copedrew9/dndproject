def build_spells():
    tags = by_tag(read_file("spells.txt"))
    out = Out(os.path.join(SRC, "gen_spells.c"), "data/spells.txt")
    out.w('#include "data.h"\n#include "data_spells.h"\n')

    schools = [r.str(0) for r in tags.get("SCHOOL", [])]
    if len(schools) != 8:
        sys.exit("data/spells.txt: expected 8 SCHOOL lines, found %d"
                 % len(schools))
    out.table("const char *const SCHOOL_NAMES[SCHOOL_COUNT]",
              ["    " + cstr(s) for s in schools])

    school_id = dict((s, "SCHOOL_" + s.upper()) for s in schools)
    rows, names = [], set()
    for r in tags.get("SPELL", []):
        if r.str(0) in names:
            r.die("%r appears twice" % r.str(0))
        names.add(r.str(0))
        bits = [c.strip() for c in r.str(10).split(",") if c.strip()]
        for c in bits:
            if c not in SPELL_CLASS_BITS:
                r.die("unknown class %r" % c)
        mask = " | ".join(SPELL_CLASS_BITS[c] for c in bits) or "0"
        rows.append(
            "    { %s, %s, %d, %s, %d, %d,\n      %s, %s,\n      %s, %s,\n"
            "      %s }"
            % (cstr(r.str(0)), lookup(BOOKS, r, 1, "book"), r.int(2),
               lookup(school_id, r, 3, "school"), r.int(4), r.int(5),
               cstr(r.str(6)), cstr(r.str(7)), cstr(r.str(8)),
               cstr(r.str(9)), mask))
    out.table("const SpellData BOOK_SPELLS[]", rows, "BOOK_SPELL_COUNT")
    out.w("\n/* Until homebrew.c says otherwise, the bank is just the"
          " book. */\n"
          "const SpellData *SPELLS = BOOK_SPELLS;\n"
          "int SPELL_COUNT =\n"
          "    (int)(sizeof(BOOK_SPELLS) / sizeof(BOOK_SPELLS[0]));\n")

    out.save()
    return names


